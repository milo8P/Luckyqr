var currentLang = localStorage.getItem('lqr_lang') || 'es';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) ||
         (I18N['es'] && I18N['es'][key]) || key;
}

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    var val = t(key);
    if (val !== undefined) el.innerHTML = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-placeholder');
    var val = t(key);
    if (val) el.placeholder = val;
  });
  document.querySelectorAll('.lang-btn').forEach(function(b) {
    b.style.opacity = b.getAttribute('data-lang') === currentLang ? '1' : '0.4';
  });
  document.documentElement.lang = currentLang;
  var ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) ogTitle.content = 'Lucky QR — ' + t('hero.chip');
}

function changeLanguage(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem('lqr_lang', lang);
  applyI18n();
}

window.addEventListener('DOMContentLoaded', function() {
  applyI18n();
});
